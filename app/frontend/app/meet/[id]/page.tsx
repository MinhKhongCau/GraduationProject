"use client";

import { useEffect, useRef, useState } from "react";
import Link from "next/link";
import { useParams, useRouter } from "next/navigation";
import { CalendarCheck, Mic, MicOff, PhoneOff, Video, VideoOff, VideoIcon, XCircle } from "lucide-react";
import { ProtectedRoute } from "@/router";
import { useAuthContext } from "@/context/AuthContext";
import { Button, buttonClasses, Card, Spinner } from "@/components/ui";
import { ROUTES } from "@/constants";
import { useMeetRoom, type MeetStatus } from "@/hooks/useMeetRoom";

const STATUS_LABEL: Record<MeetStatus, string> = {
  preparing: "Starting camera and microphone…",
  joining: "Joining the meeting…",
  waiting: "Waiting for the other participant to join…",
  connecting: "Connecting…",
  connected: "Connected",
  ended: "The session has ended",
  error: "Unable to join",
};

/** Meeting link generated by booking-service on payment: /meet/<meetingToken>. */
export default function MeetPage() {
  return (
    <ProtectedRoute allow={["PATIENT", "EXPERT", "ADMIN"]}>
      <MeetRoom />
    </ProtectedRoute>
  );
}

function MeetRoom() {
  const { id } = useParams<{ id: string }>();
  const meet = useMeetRoom(id);

  if (meet.status === "error" || meet.status === "ended") {
    return <MeetExit ended={meet.status === "ended"} message={meet.error?.message} />;
  }
  return <MeetCall meet={meet} />;
}

function dashboardHref(role?: string) {
  if (role === "EXPERT") return ROUTES.EXPERT.APPOINTMENTS;
  if (role === "ADMIN") return ROUTES.ADMIN.APPOINTMENTS;
  return ROUTES.PATIENT.MY_BOOKINGS;
}

function MeetExit({ ended, message }: { ended: boolean; message?: string }) {
  const { user } = useAuthContext();
  return (
    <div className="flex min-h-screen flex-col items-center justify-center bg-surface p-6 text-center">
      <Card className="flex w-full max-w-md flex-col items-center gap-4 p-6 sm:p-8">
        {ended ? (
          <CalendarCheck className="h-12 w-12 text-success" aria-hidden />
        ) : (
          <XCircle className="h-12 w-12 text-danger" aria-hidden />
        )}
        <h1 className="text-xl font-bold text-foreground">
          {ended ? "The session has ended" : "Unable to join the meeting"}
        </h1>
        {message && <p className="text-sm text-muted-foreground">{message}</p>}
        <Link href={dashboardHref(user?.role)} className={buttonClasses("primary", "md")}>
          Back to appointments
        </Link>
      </Card>
    </div>
  );
}

function formatDuration(totalSeconds: number) {
  const m = Math.floor(totalSeconds / 60);
  const s = totalSeconds % 60;
  return `${m}:${String(s).padStart(2, "0")}`;
}

function formatTime(ms: number | null) {
  if (!ms) return "";
  return new Date(ms).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });
}

function MeetCall({ meet }: { meet: ReturnType<typeof useMeetRoom> }) {
  const router = useRouter();
  const { user } = useAuthContext();
  const localVideoRef = useRef<HTMLVideoElement | null>(null);
  const remoteVideoRef = useRef<HTMLVideoElement | null>(null);
  const [notice, setNotice] = useState<string | null>(null);

  useEffect(() => {
    if (localVideoRef.current) localVideoRef.current.srcObject = meet.localStream;
  }, [meet.localStream]);

  useEffect(() => {
    if (remoteVideoRef.current) remoteVideoRef.current.srcObject = meet.remoteStream;
  }, [meet.remoteStream]);

  const isExpert = meet.role === "EXPERT";
  const peerLabel = isExpert ? "Patient" : "Expert";
  const showRemote = meet.remoteStream !== null;

  const handleLeave = () => {
    meet.leave();
    router.push(dashboardHref(user?.role));
  };

  const handleEnd = async () => {
    setNotice(null);
    const ack = await meet.endSession();
    if (!ack.ok) {
      setNotice(
        ack.code === "payout_pending"
          ? "Session recorded, but the payout is still pending. Try ending again in a moment."
          : ack.message ?? "Could not end the session."
      );
    }
  };

  return (
    <div className="flex min-h-screen flex-col bg-neutral-950 text-white">
      <header className="flex flex-wrap items-center justify-between gap-2 px-4 py-3 sm:px-6">
        <div className="flex items-center gap-2">
          <span
            className={
              meet.status === "connected"
                ? "h-2 w-2 rounded-full bg-success animate-pulse"
                : "h-2 w-2 rounded-full bg-warning"
            }
          />
          <span className="text-sm font-semibold">{STATUS_LABEL[meet.status]}</span>
        </div>
        {meet.startTime && meet.endTime && (
          <span className="text-xs text-neutral-400">
            {formatTime(meet.startTime)} – {formatTime(meet.endTime)}
          </span>
        )}
      </header>

      <main className="relative flex flex-1 items-center justify-center overflow-hidden px-4 pb-4 sm:px-6">
        <div className="relative h-full min-h-[60vh] w-full max-w-5xl overflow-hidden rounded-2xl border border-neutral-800 bg-black">
          <video
            ref={remoteVideoRef}
            autoPlay
            playsInline
            className={showRemote ? "h-full w-full object-cover" : "hidden"}
          />
          {!showRemote && (
            <div className="absolute inset-0 flex flex-col items-center justify-center gap-3 p-6 text-center">
              <Spinner className="h-8 w-8" />
              <p role="status" className="text-sm text-neutral-300">
                {STATUS_LABEL[meet.status]}
              </p>
            </div>
          )}
          {showRemote && (
            <div className="absolute left-4 top-4 rounded-full bg-black/50 px-3 py-1 text-xs font-semibold backdrop-blur-sm">
              {peerLabel}
            </div>
          )}

          <div className="absolute bottom-4 right-4 h-36 w-28 overflow-hidden rounded-xl border border-neutral-700 bg-neutral-800 shadow-card sm:h-44 sm:w-36">
            <video
              ref={localVideoRef}
              autoPlay
              playsInline
              muted
              className={meet.isVideoOff ? "hidden" : "h-full w-full -scale-x-100 object-cover"}
            />
            {meet.isVideoOff && (
              <div className="flex h-full w-full items-center justify-center text-neutral-400">
                <VideoOff className="h-6 w-6" aria-hidden />
              </div>
            )}
          </div>
        </div>
      </main>

      {isExpert && meet.presence && (
        <p className="px-4 text-center text-xs text-neutral-400">
          {meet.canComplete
            ? "Minimum session time reached — you can end the session."
            : `You can end the session after ${formatDuration(meet.presence.remainingSeconds)} more.`}
        </p>
      )}
      {notice && <p className="px-4 pt-1 text-center text-xs text-warning">{notice}</p>}

      <footer className="flex items-center justify-center gap-3 px-4 py-4">
        <Button
          variant="ghost"
          size="icon"
          onClick={meet.toggleMute}
          aria-label={meet.isMuted ? "Unmute" : "Mute"}
          className="rounded-full bg-neutral-800 text-white hover:bg-neutral-700"
        >
          {meet.isMuted ? <MicOff className="h-5 w-5" /> : <Mic className="h-5 w-5" />}
        </Button>
        <Button
          variant="ghost"
          size="icon"
          onClick={meet.toggleVideo}
          disabled={!meet.hasCamera}
          aria-label={meet.isVideoOff ? "Turn camera on" : "Turn camera off"}
          className="rounded-full bg-neutral-800 text-white hover:bg-neutral-700"
        >
          {meet.isVideoOff ? <VideoOff className="h-5 w-5" /> : <Video className="h-5 w-5" />}
        </Button>
        <Button variant="danger" onClick={handleLeave} className="rounded-full">
          <PhoneOff className="h-5 w-5" aria-hidden />
          Leave
        </Button>
        {isExpert && (
          <Button
            variant="primary"
            onClick={handleEnd}
            disabled={!meet.canComplete || meet.isEnding}
            className="rounded-full"
          >
            <VideoIcon className="h-5 w-5" aria-hidden />
            {meet.isEnding ? "Ending…" : "End session"}
          </Button>
        )}
      </footer>
    </div>
  );
}
